package google

import (
	"bytes"
	"compress/gzip"
	"encoding/base64"
	"fmt"
	"io"
	"slices"
	"strings"

	"github.com/rancher/machine/libmachine/log"
	"gopkg.in/yaml.v3"
)

const startupScriptDoneFile = "/var/lib/rancher-machine/startup-script.done"

type cloudConfig struct {
	Hostname   string      `yaml:"hostname"`
	WriteFiles []writeFile `yaml:"write_files"`
	RunCmd     []any       `yaml:"runcmd"`
}

type writeFile struct {
	Path        string `yaml:"path"`
	Content     string `yaml:"content"`
	Encoding    string `yaml:"encoding"`
	Permissions string `yaml:"permissions"`
	Owner       string `yaml:"owner"`
	Append      bool   `yaml:"append"`
}

// startupScript translates userdata into a GCE startup-script. Some images (openSUSE and SUSE among them)
// ship the Google guest environment instead of cloud-init, so the user-data metadata key is never read there.
// The script exits right away on images that have cloud-init, so the userdata never runs twice.
func startupScript(userdata string) (string, error) {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by rancher-machine from user-data, for images without cloud-init.\n")
	b.WriteString("command -v cloud-init >/dev/null 2>&1 && exit 0\n")
	fmt.Fprintf(&b, "[ -e %[1]s ] && exit 0\nmkdir -p \"$(dirname %[1]s)\" && touch %[1]s\n", startupScriptDoneFile)

	if strings.HasPrefix(userdata, "#!") {
		b.WriteString("f=$(mktemp) && cat > \"$f\" <<'RANCHER_MACHINE_EOF'\n")
		b.WriteString(strings.TrimSuffix(userdata, "\n"))
		b.WriteString("\nRANCHER_MACHINE_EOF\nchmod +x \"$f\" && exec \"$f\"\n")
		return b.String(), nil
	}

	var raw map[string]any
	if err := yaml.Unmarshal([]byte(userdata), &raw); err != nil {
		return "", fmt.Errorf("parsing userdata as cloud-config: %w", err)
	}
	for key := range raw {
		if !slices.Contains([]string{"hostname", "write_files", "runcmd"}, key) {
			log.Warnf("cloud-config key %q is ignored on images without cloud-init", key)
		}
	}
	var cc cloudConfig
	if err := yaml.Unmarshal([]byte(userdata), &cc); err != nil {
		return "", fmt.Errorf("parsing userdata as cloud-config: %w", err)
	}

	b.WriteString("set -e\n")
	if cc.Hostname != "" {
		fmt.Fprintf(&b, "hostnamectl set-hostname %s\n", shellQuote(cc.Hostname))
	}
	for _, f := range cc.WriteFiles {
		content, err := decodeContent(f.Content, f.Encoding)
		if err != nil {
			return "", fmt.Errorf("write_files %s: %w", f.Path, err)
		}
		path := shellQuote(f.Path)
		redirect := ">"
		if f.Append {
			redirect = ">>"
		}
		fmt.Fprintf(&b, "mkdir -p \"$(dirname %s)\"\n", path)
		fmt.Fprintf(&b, "base64 -d %s %s <<'RANCHER_MACHINE_EOF'\n%s\nRANCHER_MACHINE_EOF\n", redirect, path, base64.StdEncoding.EncodeToString(content))
		perms := f.Permissions
		if perms == "" {
			perms = "0644"
		}
		fmt.Fprintf(&b, "chmod %s %s\n", shellQuote(perms), path)
		if f.Owner != "" {
			fmt.Fprintf(&b, "chown %s %s\n", shellQuote(f.Owner), path)
		}
	}

	// cloud-init keeps going when a runcmd entry fails.
	b.WriteString("set +e\n")
	for _, cmd := range cc.RunCmd {
		switch c := cmd.(type) {
		case string:
			b.WriteString(c + "\n")
		case []any:
			args := make([]string, len(c))
			for i, a := range c {
				args[i] = shellQuote(fmt.Sprint(a))
			}
			b.WriteString(strings.Join(args, " ") + "\n")
		default:
			return "", fmt.Errorf("unsupported runcmd entry %v", cmd)
		}
	}
	return b.String(), nil
}

func decodeContent(content, encoding string) ([]byte, error) {
	switch strings.ToLower(encoding) {
	case "", "text/plain":
		return []byte(content), nil
	case "b64", "base64":
		return base64.StdEncoding.DecodeString(content)
	case "gz", "gzip":
		return gunzip([]byte(content))
	case "gz+b64", "gz+base64", "gzip+b64", "gzip+base64":
		data, err := base64.StdEncoding.DecodeString(content)
		if err != nil {
			return nil, err
		}
		return gunzip(data)
	}
	return nil, fmt.Errorf("unsupported encoding %q", encoding)
}

func gunzip(data []byte) ([]byte, error) {
	r, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		return nil, err
	}
	return io.ReadAll(r)
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
